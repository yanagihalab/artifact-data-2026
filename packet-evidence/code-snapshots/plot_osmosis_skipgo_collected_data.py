#!/usr/bin/env python3
"""
Plot already-collected Osmosis Skip Go block-data analysis outputs.

This script does NOT fetch chain data.
It reads files generated by analyze_osmosis_skipgo_contracts_blockdata.py / v2:

  required:
    per_height.csv
    contracts_summary.csv
    summary.json

  optional:
    txs.csv
    entry_point_actions.csv
    cooccurrence_counts.csv
    contract_flow_counts.csv
    message_action_counts.csv
    message_type_counts.csv

Typical usage:
  python3 plot_osmosis_skipgo_collected_data.py \
    --input-dir osmosis_skipgo_3contracts_61161000_61170000_raw_matching \
    --out-dir osmosis_skipgo_3contracts_61161000_61170000_plots

With rolling window:
  python3 plot_osmosis_skipgo_collected_data.py \
    --input-dir osmosis_skipgo_3contracts_61161000_61170000_raw_matching \
    --out-dir osmosis_skipgo_3contracts_61161000_61170000_plots \
    --rolling-window 100

Output:
  PNG plots
  plot_summary.md
  plot_summary.json
"""

from __future__ import annotations

import argparse
import csv
import json
import math
import re
from collections import Counter
from pathlib import Path
from typing import Any, Iterable

try:
    import matplotlib.pyplot as plt
except ImportError as exc:
    raise SystemExit("Missing dependency: matplotlib. Install with: pip install matplotlib") from exc


Json = dict[str, Any]


def ensure_dir(path: Path) -> None:
    path.mkdir(parents=True, exist_ok=True)


def read_csv(path: Path) -> list[Json]:
    if not path.exists():
        return []
    with path.open("r", encoding="utf-8", newline="") as f:
        return [dict(row) for row in csv.DictReader(f)]


def read_json(path: Path) -> Json:
    if not path.exists():
        return {}
    return json.loads(path.read_text(encoding="utf-8"))


def to_int(value: Any, default: int = 0) -> int:
    if value is None:
        return default
    s = str(value).strip()
    if s == "":
        return default
    try:
        return int(float(s))
    except Exception:
        return default


def to_float(value: Any, default: float = 0.0) -> float:
    if value is None:
        return default
    s = str(value).strip()
    if s == "":
        return default
    try:
        return float(s)
    except Exception:
        return default


def parse_uosmo(value: Any) -> int:
    if value is None:
        return 0
    total = 0
    for part in str(value).split(";"):
        m = re.fullmatch(r"(\d+)uosmo", part.strip())
        if m:
            total += int(m.group(1))
    return total


def safe_filename(label: str) -> str:
    return re.sub(r"[^A-Za-z0-9_.-]+", "_", label).strip("_")


def write_csv(path: Path, rows: Iterable[Json], fields: list[str]) -> None:
    with path.open("w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields, extrasaction="ignore")
        w.writeheader()
        for row in rows:
            w.writerow(row)


def top_n_rows(rows: list[Json], key_field: str, count_field: str = "count", n: int = 30) -> list[Json]:
    return sorted(rows, key=lambda r: (-to_int(r.get(count_field)), str(r.get(key_field, ""))))[:n]


def moving_sum(values: list[int], window: int) -> list[int]:
    if window <= 1:
        return list(values)
    out: list[int] = []
    running = 0
    q: list[int] = []
    for value in values:
        q.append(value)
        running += value
        if len(q) > window:
            running -= q.pop(0)
        out.append(running)
    return out


def plot_line(x: list[int], y: list[int | float], title: str, xlabel: str, ylabel: str, path: Path) -> None:
    if not x or not any(float(v) != 0 for v in y):
        return
    plt.figure(figsize=(13, 6))
    plt.plot(x, y)
    plt.xlabel(xlabel)
    plt.ylabel(ylabel)
    plt.title(title)
    plt.tight_layout()
    plt.savefig(path, dpi=160)
    plt.close()


def plot_bar(labels: list[str], values: list[int | float], title: str, xlabel: str, ylabel: str, path: Path, rotate: bool = True) -> None:
    if not labels or not any(float(v) != 0 for v in values):
        return
    plt.figure(figsize=(12, 7))
    plt.bar(labels, values)
    plt.xlabel(xlabel)
    plt.ylabel(ylabel)
    plt.title(title)
    if rotate:
        plt.xticks(rotation=35, ha="right")
    plt.tight_layout()
    plt.savefig(path, dpi=160)
    plt.close()


def plot_hist(values: list[int | float], bins: int, title: str, xlabel: str, ylabel: str, path: Path) -> None:
    values = [v for v in values if v is not None]
    if not values:
        return
    plt.figure(figsize=(10, 6))
    plt.hist(values, bins=bins)
    plt.xlabel(xlabel)
    plt.ylabel(ylabel)
    plt.title(title)
    plt.tight_layout()
    plt.savefig(path, dpi=160)
    plt.close()


def plot_scatter(x: list[int | float], y: list[int | float], title: str, xlabel: str, ylabel: str, path: Path) -> None:
    if not x or not y:
        return
    plt.figure(figsize=(10, 6))
    plt.scatter(x, y)
    plt.xlabel(xlabel)
    plt.ylabel(ylabel)
    plt.title(title)
    plt.tight_layout()
    plt.savefig(path, dpi=160)
    plt.close()


def detect_contract_names(per_height_rows: list[Json], contracts_summary_rows: list[Json]) -> list[str]:
    names: list[str] = []
    for row in contracts_summary_rows:
        name = row.get("contract")
        if name:
            names.append(str(name))
    if names:
        return names

    if per_height_rows:
        keys = per_height_rows[0].keys()
        for key in keys:
            if key.endswith("_tx_count") and key != "tx_count_any_target":
                names.append(key[:-len("_tx_count")])
    return names


def generate_per_height_plots(
    per_height: list[Json],
    contracts: list[str],
    out_dir: Path,
    rolling_window: int,
    generated: list[str],
) -> None:
    if not per_height:
        return

    heights = [to_int(r.get("height")) for r in per_height]

    any_target = [to_int(r.get("tx_count_any_target")) for r in per_height]
    if any(any_target):
        p = out_dir / "any_target_tx_count_by_height.png"
        plot_line(heights, any_target, "Any target contract: TX count by height", "block height", "tx count", p)
        generated.append(str(p))

        cumulative = []
        running = 0
        for v in any_target:
            running += v
            cumulative.append(running)
        p = out_dir / "any_target_tx_count_cumulative.png"
        plot_line(heights, cumulative, "Any target contract: cumulative TX count", "block height", "cumulative tx count", p)
        generated.append(str(p))

        if rolling_window > 1:
            p = out_dir / f"any_target_tx_count_rolling_{rolling_window}_blocks.png"
            plot_line(
                heights,
                moving_sum(any_target, rolling_window),
                f"Any target contract: rolling {rolling_window}-block TX count",
                "block height",
                f"rolling {rolling_window}-block tx count",
                p,
            )
            generated.append(str(p))

    for contract in contracts:
        series = [
            (f"{contract}_tx_count", "TX count", "tx_count"),
            (f"{contract}_execute_event_count", "execute event count", "execute_events"),
            (f"{contract}_wasm_event_count", "wasm event count", "wasm_events"),
            (f"{contract}_direct_msg_count", "direct MsgExecuteContract count", "direct_msgs"),
        ]
        for column, label, suffix in series:
            values = [to_int(r.get(column)) for r in per_height]
            if not any(values):
                continue

            filename = f"{safe_filename(contract)}_{suffix}_by_height.png"
            p = out_dir / filename
            plot_line(heights, values, f"{contract}: {label} by height", "block height", label, p)
            generated.append(str(p))

            cumulative = []
            running = 0
            for v in values:
                running += v
                cumulative.append(running)
            p = out_dir / f"{safe_filename(contract)}_{suffix}_cumulative.png"
            plot_line(heights, cumulative, f"{contract}: cumulative {label}", "block height", f"cumulative {label}", p)
            generated.append(str(p))

            if rolling_window > 1:
                p = out_dir / f"{safe_filename(contract)}_{suffix}_rolling_{rolling_window}_blocks.png"
                plot_line(
                    heights,
                    moving_sum(values, rolling_window),
                    f"{contract}: rolling {rolling_window}-block {label}",
                    "block height",
                    f"rolling {rolling_window}-block {label}",
                    p,
                )
                generated.append(str(p))


def generate_contract_summary_plots(rows: list[Json], out_dir: Path, generated: list[str]) -> None:
    if not rows:
        return

    labels = [str(r.get("contract", "")) for r in rows]
    metrics = [
        ("tx_count", "TX count"),
        ("execute_event_count", "Execute event count"),
        ("wasm_event_count", "Wasm event count"),
        ("other_event_count", "Other event count"),
        ("direct_msg_count", "Direct MsgExecuteContract count"),
        ("blocks_with_hits", "Blocks with hits"),
    ]

    for field, title in metrics:
        values = [to_int(r.get(field)) for r in rows]
        if not any(values):
            continue
        p = out_dir / f"contract_summary_{field}.png"
        plot_bar(labels, values, f"Contract summary: {title}", "contract", title, p)
        generated.append(str(p))


def generate_count_csv_plots(
    input_dir: Path,
    out_dir: Path,
    generated: list[str],
    max_bars: int,
) -> None:
    count_files = [
        ("cooccurrence_counts.csv", "matched_contracts", "Co-occurrence counts", "cooccurrence_counts.png"),
        ("contract_flow_counts.csv", "contract_flow", "Contract flow counts", "contract_flow_counts.png"),
        ("message_action_counts.csv", "message_action", "Message action counts", "message_action_counts.png"),
        ("message_type_counts.csv", "message_type", "Message type counts", "message_type_counts.png"),
    ]

    for filename, key_field, title, output_name in count_files:
        rows = read_csv(input_dir / filename)
        if not rows:
            continue
        top = top_n_rows(rows, key_field, "count", max_bars)
        labels = [str(r.get(key_field, "")) for r in top]
        values = [to_int(r.get("count")) for r in top]
        p = out_dir / output_name
        plot_bar(labels, values, title, key_field, "count", p)
        generated.append(str(p))


def generate_txs_plots(txs: list[Json], out_dir: Path, generated: list[str]) -> None:
    if not txs:
        return

    fee_osmo = [parse_uosmo(r.get("fee_amount")) / 1_000_000 for r in txs]
    gas_used = [to_int(r.get("gas_used")) for r in txs]
    gas_wanted = [to_int(r.get("gas_wanted")) for r in txs]

    if fee_osmo:
        p = out_dir / "tx_fee_osmo_histogram.png"
        plot_hist(fee_osmo, bins=min(40, max(8, int(math.sqrt(len(fee_osmo))) + 1)), title="TX fee distribution", xlabel="fee (OSMO)", ylabel="tx count", path=p)
        generated.append(str(p))

    if gas_used:
        p = out_dir / "tx_gas_used_histogram.png"
        plot_hist(gas_used, bins=min(40, max(8, int(math.sqrt(len(gas_used))) + 1)), title="TX gas used distribution", xlabel="gas used", ylabel="tx count", path=p)
        generated.append(str(p))

    if gas_wanted:
        p = out_dir / "tx_gas_wanted_histogram.png"
        plot_hist(gas_wanted, bins=min(40, max(8, int(math.sqrt(len(gas_wanted))) + 1)), title="TX gas wanted distribution", xlabel="gas wanted", ylabel="tx count", path=p)
        generated.append(str(p))

    if fee_osmo and gas_used:
        p = out_dir / "tx_fee_vs_gas_used.png"
        plot_scatter(gas_used, fee_osmo, "Fee vs gas used", "gas used", "fee (OSMO)", p)
        generated.append(str(p))

    success = Counter(str(r.get("success", "")) for r in txs)
    p = out_dir / "tx_success_counts.png"
    plot_bar(list(success.keys()), list(success.values()), "TX success counts", "success", "count", p, rotate=False)
    generated.append(str(p))

    matched = Counter(str(r.get("matched_contracts", "")) for r in txs if r.get("matched_contracts"))
    if matched:
        labels, values = zip(*matched.most_common(30))
        p = out_dir / "tx_matched_contracts_counts.png"
        plot_bar(list(labels), list(values), "Matched contracts per TX", "matched_contracts", "tx count", p)
        generated.append(str(p))


def generate_entry_action_plots(actions: list[Json], out_dir: Path, generated: list[str], max_bars: int) -> None:
    if not actions:
        return

    fields = [
        ("post_swap_action_type", "Post-swap action type", "entry_post_swap_action_type_counts.png"),
        ("swap_mode", "Swap mode", "entry_swap_mode_counts.png"),
        ("swap_venue", "Swap venue", "entry_swap_venue_counts.png"),
        ("source_channel", "IBC source channel", "entry_ibc_source_channel_counts.png"),
        ("min_asset_denom", "Min asset denom", "entry_min_asset_denom_counts.png"),
    ]

    for field, title, filename in fields:
        c = Counter(str(r.get(field, "") or "none") for r in actions)
        if not c:
            continue
        labels, values = zip(*c.most_common(max_bars))
        p = out_dir / filename
        plot_bar(list(labels), list(values), title, field, "count", p)
        generated.append(str(p))

    pool_counts = Counter()
    denom_in_counts = Counter()
    denom_out_counts = Counter()

    for row in actions:
        for pool in str(row.get("pool_ids", "")).split(";"):
            if pool:
                pool_counts[pool] += 1
        for denom in str(row.get("denoms_in", "")).split(";"):
            if denom:
                denom_in_counts[denom] += 1
        for denom in str(row.get("denoms_out", "")).split(";"):
            if denom:
                denom_out_counts[denom] += 1

    for counter, title, filename, xlabel in [
        (pool_counts, "Pool usage", "entry_pool_usage_counts.png", "pool id"),
        (denom_in_counts, "Input denom usage", "entry_denom_in_counts.png", "denom_in"),
        (denom_out_counts, "Output denom usage", "entry_denom_out_counts.png", "denom_out"),
    ]:
        if not counter:
            continue
        labels, values = zip(*counter.most_common(max_bars))
        p = out_dir / filename
        plot_bar(list(labels), list(values), title, xlabel, "count", p)
        generated.append(str(p))

    swap_operation_counts = [to_int(r.get("swap_operation_count")) for r in actions if str(r.get("swap_operation_count", "")) != ""]
    if swap_operation_counts:
        p = out_dir / "entry_swap_operation_count_histogram.png"
        plot_hist(swap_operation_counts, bins=range(0, max(swap_operation_counts) + 2), title="Swap operation count distribution", xlabel="swap operation count", ylabel="row count", path=p)
        generated.append(str(p))

    affiliate_counts = [to_int(r.get("affiliate_count")) for r in actions if str(r.get("affiliate_count", "")) != ""]
    if affiliate_counts:
        p = out_dir / "entry_affiliate_count_histogram.png"
        plot_hist(affiliate_counts, bins=range(0, max(affiliate_counts) + 2), title="Affiliate count distribution", xlabel="affiliate count", ylabel="row count", path=p)
        generated.append(str(p))

    affiliate_bps = [to_int(r.get("affiliate_bps_total")) for r in actions if str(r.get("affiliate_bps_total", "")) != ""]
    if affiliate_bps:
        p = out_dir / "entry_affiliate_bps_total_histogram.png"
        plot_hist(affiliate_bps, bins=min(20, max(5, int(math.sqrt(len(affiliate_bps))) + 1)), title="Affiliate total bps distribution", xlabel="affiliate total bps", ylabel="row count", path=p)
        generated.append(str(p))


def write_summary(out_dir: Path, input_dir: Path, generated: list[str], summary: Json) -> None:
    lines = []
    lines.append("# Osmosis Skip Go Collected Data Plot Summary")
    lines.append("")
    lines.append(f"Input directory: `{input_dir}`")
    lines.append("")
    lines.append("## Data summary")
    lines.append("")
    lines.append("| Metric | Value |")
    lines.append("|---|---:|")
    for key, value in summary.items():
        if key == "generated_files":
            continue
        lines.append(f"| {key} | `{value}` |")
    lines.append("")
    lines.append("## Generated plots")
    lines.append("")
    for path in generated:
        lines.append(f"- `{Path(path).name}`")
    (out_dir / "plot_summary.md").write_text("\n".join(lines), encoding="utf-8")
    (out_dir / "plot_summary.json").write_text(json.dumps({**summary, "generated_files": generated}, indent=2, ensure_ascii=False), encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description="Plot collected Osmosis Skip Go analysis data.")
    parser.add_argument("--input-dir", required=True, help="Directory generated by analyze_osmosis_skipgo_contracts_blockdata.py/v2.")
    parser.add_argument("--out-dir", required=True, help="Directory to write plots.")
    parser.add_argument("--rolling-window", type=int, default=0, help="Optional rolling window size in blocks, e.g. 100.")
    parser.add_argument("--max-bars", type=int, default=30, help="Max bars for categorical charts.")
    args = parser.parse_args()

    input_dir = Path(args.input_dir)
    out_dir = Path(args.out_dir)
    ensure_dir(out_dir)

    summary_json = read_json(input_dir / "summary.json")
    per_height = read_csv(input_dir / "per_height.csv")
    contracts_summary = read_csv(input_dir / "contracts_summary.csv")
    txs = read_csv(input_dir / "txs.csv")
    actions = read_csv(input_dir / "entry_point_actions.csv")

    contracts = detect_contract_names(per_height, contracts_summary)
    generated: list[str] = []

    generate_per_height_plots(per_height, contracts, out_dir, max(0, args.rolling_window), generated)
    generate_contract_summary_plots(contracts_summary, out_dir, generated)
    generate_count_csv_plots(input_dir, out_dir, generated, args.max_bars)
    generate_txs_plots(txs, out_dir, generated)
    generate_entry_action_plots(actions, out_dir, generated, args.max_bars)

    data_summary = {
        "contracts": ",".join(contracts),
        "per_height_rows": len(per_height),
        "contracts_summary_rows": len(contracts_summary),
        "tx_rows": len(txs),
        "entry_point_action_rows": len(actions),
        "plots_generated": len(generated),
        "from_height": summary_json.get("from_height", ""),
        "to_height": summary_json.get("to_height", ""),
        "tx_count_any_target": summary_json.get("tx_count_any_target", ""),
        "blocks_scanned": summary_json.get("blocks_scanned", ""),
        "blocks_failed": summary_json.get("blocks_failed", ""),
    }

    write_summary(out_dir, input_dir, generated, data_summary)

    print(json.dumps(data_summary, ensure_ascii=False))
    print(f"Plot summary written: {out_dir / 'plot_summary.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
